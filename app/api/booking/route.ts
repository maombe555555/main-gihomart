import dbConnect from "@/lib/mongodb"
import Booking from "@/models/Booking"
import { z } from "zod"
import { sendMail } from "@/lib/mail"

// GET - Fetch all bookings with optional filtering
export async function GET(req: Request) {
  if (!process.env.MONGODB_URI) {
    return Response.json({ error: "Database not configured" }, { status: 503 })
  }
  
  try {
    await dbConnect()
    
    // Get query parameters
    const { searchParams } = new URL(req.url)
    const page = parseInt(searchParams.get('page') || '1')
    const limit = parseInt(searchParams.get('limit') || '10')
    const status = searchParams.get('status')
    const email = searchParams.get('email')
    const search = searchParams.get('search')
    
    // Build query
    let query: any = {}
    
    if (status) query.status = status
    if (email) query.email = email
    if (search) {
      query.$or = [
        { firstName: { $regex: search, $options: 'i' } },
        { lastName: { $regex: search, $options: 'i' } },
        { email: { $regex: search, $options: 'i' } },
        { residence: { $regex: search, $options: 'i' } }
      ]
    }
    
    // Calculate pagination
    const skip = (page - 1) * limit
    
    // Execute queries
    const [bookings, total] = await Promise.all([
      Booking.find(query)
        .select("_id firstName lastName email phone residence departureDate returnDate travelers budget comments products status statusUpdatedAt createdAt")
        .sort({ createdAt: -1 })
        .skip(skip)
        .limit(limit)
        .lean(),
      Booking.countDocuments(query)
    ])
    
    const totalPages = Math.ceil(total / limit)
    
    return Response.json({
      success: true,
      data: bookings,
      pagination: {
        page,
        limit,
        total,
        totalPages,
        hasNext: page < totalPages,
        hasPrev: page > 1
      }
    })
    
  } catch (error) {
    console.error('Failed to fetch bookings:', error)
    return Response.json({ error: "Failed to fetch bookings" }, { status: 500 })
  }
}

