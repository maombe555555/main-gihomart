// PUT - Update booking status (approve, waiting, reject)
export async function PUT(req: Request) {
  if (!process.env.MONGODB_URI) {
    return Response.json({ error: "Database not configured" }, { status: 503 })
  }

  const body = await req.json().catch(() => ({}))
  
  const schema = z.object({
    id: z.string().min(1, "Booking ID is required"),
    status: z.enum(['approved', 'waiting', 'rejected', 'pending']),
    adminComments: z.string().optional().default("")
  })
  
  const parsed = schema.safeParse(body)
  if (!parsed.success) {
    return Response.json(
      { error: "Invalid input", details: parsed.error.flatten() },
      { status: 400 }
    )
  }

  try {
    await dbConnect()
    
    const { id, status, adminComments } = parsed.data
    
    // Find and update booking
    const booking = await Booking.findByIdAndUpdate(
      id,
      { 
        status, 
        statusUpdatedAt: new Date() 
      },
      { new: true }
    )
    
    if (!booking) {
      return Response.json({ error: "Booking not found" }, { status: 404 })
    }

    // Send status update email to customer
    try {
      const fullName = `${booking.firstName} ${booking.lastName}`.trim()
      let subject = ''
      let html = ''

      switch (status) {
        case 'approved':
          subject = 'Your Booking Has Been Approved!'
          html = `
            <h2>Booking Approved!</h2>
            <p>Dear ${fullName},</p>
            <p>Great news! Your booking has been approved.</p>
            <p>We're excited to help you with your travel plans!</p>
            ${adminComments ? `<p><strong>Additional comments:</strong> ${adminComments}</p>` : ""}
            <br>
            <p>Best regards,<br>Your Travel Team</p>
          `
          break
        case 'waiting':
          subject = 'Your Booking Status Update'
          html = `
            <h2>Booking Status Update</h2>
            <p>Dear ${fullName},</p>
            <p>Your booking has been placed on the waiting list.</p>
            <p>We'll notify you as soon as spots become available.</p>
            ${adminComments ? `<p><strong>Additional comments:</strong> ${adminComments}</p>` : ""}
            <br>
            <p>Best regards,<br>Your Travel Team</p>
          `
          break
        case 'rejected':
          subject = 'Update on Your Booking Request'
          html = `
            <h2>Booking Update</h2>
            <p>Dear ${fullName},</p>
            <p>Unfortunately, your booking could not be processed at this time.</p>
            ${adminComments ? `<p><strong>Reason:</strong> ${adminComments}</p>` : ""}
            <br>
            <p>Best regards,<br>Your Travel Team</p>
          `
          break
        default:
          subject = 'Booking Status Update'
          html = `
            <h2>Booking Status Update</h2>
            <p>Dear ${fullName},</p>
            <p>Your booking status has been updated to: ${status}</p>
            ${adminComments ? `<p><strong>Comments:</strong> ${adminComments}</p>` : ""}
            <br>
            <p>Best regards,<br>Your Travel Team</p>
          `
      }

      await sendMail({ 
        to: booking.email, 
        subject, 
        html 
      })

    } catch (emailError) {
      console.error('Status update email failed:', emailError)
      // Continue even if email fails
    }

    return Response.json({ 
      success: true, 
      message: `Booking ${status} successfully`,
      data: booking 
    })
    
  } catch (error) {
    console.error('Failed to update booking:', error)
    return Response.json({ error: "Failed to update booking" }, { status: 500 })
  }
}

// DELETE - Remove booking
export async function DELETE(req: Request) {
  if (!process.env.MONGODB_URI) {
    return Response.json({ error: "Database not configured" }, { status: 503 })
  }

  const { searchParams } = new URL(req.url)
  const id = searchParams.get('id')
  
  if (!id) {
    return Response.json({ error: "Booking ID is required" }, { status: 400 })
  }

  try {
    await dbConnect()
    
    const booking = await Booking.findByIdAndDelete(id)
    
    if (!booking) {
      return Response.json({ error: "Booking not found" }, { status: 404 })
    }

    return Response.json({ 
      success: true, 
      message: "Booking deleted successfully" 
    })
    
  } catch (error) {
    console.error('Failed to delete booking:', error)
    return Response.json({ error: "Failed to delete booking" }, { status: 500 })
  }
}